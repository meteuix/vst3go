// EditorBindings returns a TypeScript module with typed bindings to the
// parameters of p for a custom editor page: a params table keyed by
// camel-cased parameter names with each parameter's ID, range and kind, and
// param(key) returning the live SDK parameter. defaultValue is plain.
// Hidden parameters (MIDI controller mappings) are left out.
func EditorBindings(p Plugin) (string, error) {
	info := p.GetInfo()
	c, err := newComponent(p.CreateProcessor(), info)
	if err != nil {
		return "", err
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by vst3go (plugin.EditorBindings) for %s; DO NOT EDIT.\n", info.Name)
	b.WriteString("/// <reference path=\"./vst3go.d.ts\" />\n\n")
	b.WriteString("export const params = {\n")
	used := map[string]bool{}
	for _, prm := range c.params.All() {
		if prm.Flags&param.IsHidden != 0 {
			continue
		}
		key := bindingKey(prm.Name)
		if used[key] {
			key = fmt.Sprintf("%s%d", key, prm.ID)
		}
		used[key] = true
		fmt.Fprintf(&b, "  %s: { id: %d, name: %s, unit: %s, kind: %q, min: %s, max: %s, defaultValue: %s, stepCount: %d },\n",
			key, prm.ID, strconv.Quote(prm.Name), strconv.Quote(prm.Unit), inferControlKind(prm),
			jsNumber(prm.Min), jsNumber(prm.Max), jsNumber(prm.Denormalize(prm.DefaultValue)), prm.StepCount)
	}
	b.WriteString("} as const;\n\n")
	b.WriteString("export type ParamKey = keyof typeof params;\n\n")
	b.WriteString("/** param returns the live SDK parameter of a key. */\n")
	b.WriteString("export function param(key: ParamKey): Vst3goParam {\n")
	b.WriteString("  const p = vst3go.param(params[key].id);\n")
	b.WriteString("  if (!p) throw new Error(`vst3go: no parameter ${params[key].id} (${key}); regenerate the bindings`);\n")
	b.WriteString("  return p;\n")
	b.WriteString("}\n")
	return b.String(), nil
}

// WriteEditorBindings writes the SDK declarations (vst3go.d.ts) and the
// EditorBindings of p (params.ts) into dir, e.g. from a go:generate program
// or a test of the plugin package.
func WriteEditorBindings(p Plugin, dir string) error {
	bindings, err := EditorBindings(p)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(dir, "vst3go.d.ts"), []byte(EditorSDKTypes()), 0o644); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(dir, "params.ts"), []byte(bindings), 0o644)
}

// bindingKey turns a parameter name into a camel-case identifier:
// "Cutoff Freq" -> cutoffFreq, "2nd Osc" -> p2ndOsc.
func bindingKey(name string) string {
	var b strings.Builder
	upper := false
	for _, r := range name {
		if !unicode.IsLetter(r) && !unicode.IsDigit(r) || r > unicode.MaxASCII {
			upper = b.Len() > 0
			continue
		}
		switch {
		case b.Len() == 0:
			if unicode.IsDigit(r) {
				b.WriteByte('p')
			}
			b.WriteRune(unicode.ToLower(r))
		case upper:
			b.WriteRune(unicode.ToUpper(r))
		default:
			b.WriteRune(r)
		}
		upper = false
	}
	if b.Len() == 0 {
		return "param"
	}
	return b.String()
}

func jsNumber(v float64) string {
	switch {
	case math.IsInf(v, 1):
		return "Infinity"
	case math.IsInf(v, -1):
		return "-Infinity"
	case math.IsNaN(v):
		return "NaN"
	}
	return strconv.FormatFloat(v, 'g', 12, 64) // 12 digits drop float noise (-12.000000000000004)
}
